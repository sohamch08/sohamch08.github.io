#!/usr/bin/env python3
"""Check Hugo's routes, local links, offline resources, and key downloads."""
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit
import json
import re
import sys
import xml.etree.ElementTree as ET

root = Path(sys.argv[1] if len(sys.argv) > 1 else 'public').resolve()
routes = ['index.html', 'publications/index.html', 'courses/index.html',
          'projects-talks/index.html', 'misc/index.html', 'resources/index.html',
          'contact/index.html', '404.html']

class Document(HTMLParser):
    def __init__(self, text):
        super().__init__(convert_charrefs=True)
        self.links, self.ids = [], set()
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs:
            self.ids.add(attrs['id'])
        for name in ('href', 'src'):
            if attrs.get(name):
                self.links.append(attrs[name])

errors = []
documents = {}
for route in routes:
    path = root / route
    if not path.is_file():
        errors.append(f'Missing route: {route}')
        continue
    text = path.read_text()
    if '{%' in text or re.search(r'{{[<%]?', text):
        errors.append(f'Unprocessed template in {route}')
    if 'name=generator content="Hugo' not in text and 'name="generator" content="Hugo' not in text:
        errors.append(f'Not generated by Hugo: {route}')
    if '<pre><code>&lt;' in text or re.search(r'(^|>)\s*##?\s', text):
        errors.append(f'HTML rendered as code in {route}')
    documents[path] = Document(text)

for path, doc in documents.items():
    for href in doc.links:
        link = urlsplit(href)
        if link.scheme or link.netloc:
            continue
        target = root / unquote(link.path.lstrip('/')) if link.path.startswith('/') else path.parent / unquote(link.path)
        if not link.path:
            target = path
        if target.is_dir():
            target /= 'index.html'
        if not target.is_file():
            errors.append(f'{path.relative_to(root)}: missing {href}')
        elif link.fragment and target.suffix == '.html':
            target_doc = documents.get(target) or Document(target.read_text())
            if unquote(link.fragment) not in target_doc.ids:
                errors.append(f'{path.relative_to(root)}: missing anchor {href}')

for name in ['feed.xml', 'sitemap.xml']:
    ET.parse(root / name)
assert json.loads((root / 'assets/js/data/search.json').read_text()) == []
assets = Path(__file__).resolve().parent.parent / 'assets'
for filename, source, marker in [('gpg.asc', 'gpg_key.asc', 'BEGIN PGP PUBLIC KEY BLOCK'),
                                 ('ssh.pub', 'id_ed25519.pub', ' ')]:
    text = (root / 'assets/keys' / filename).read_text()
    if marker not in text or '{{' in text:
        errors.append(f'Invalid download: {filename}')
    if (root / 'assets/keys' / filename).read_bytes() != (assets / source).read_bytes():
        errors.append(f'Key download differs from asset: {filename}')

contact = (root / 'contact/index.html').read_text()
key_sources = re.findall(r'<textarea\b[^>]*id=["\']?([^\s"\'>]+)["\']?[^>]*>(.*?)</textarea>', contact, re.S)
from html import unescape
for key_id, text in key_sources:
    filename = 'gpg.asc' if key_id == 'gpg-key' else 'ssh.pub'
    if unescape(text).strip() != (root / 'assets/keys' / filename).read_text().strip():
        errors.append(f'Key source differs from download: {key_id}')
if len(key_sources) != 2:
    errors.append('Contact must contain both public key sources')

swconf = (root / 'assets/js/data/swconf.js').read_text()
for resource in re.findall(r'"(/[^"\n]*)"', swconf):
    path = root / resource.lstrip('/')
    if path.is_dir():
        path /= 'index.html'
    if not path.is_file():
        errors.append(f'Missing offline resource: {resource}')
for script in [root / 'app.min.js', root / 'sw.min.js']:
    if script.read_text().startswith('---'):
        errors.append(f'Front matter in served JavaScript: {script.name}')

if errors:
    raise SystemExit('\n'.join(sorted(set(errors))))
print(f'Checked {len(documents)} pages, local links, feeds, offline resources, and public keys.')
